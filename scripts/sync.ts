// Regenerate src/episodes.generated.ts (one import per episode folder) and episodes/episode.schema.json.
// Usage: npm run sync
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { episodeSchema } from "../src/kit/schema.ts";
import { isMain, ok, paths, ROOT, SLUG_RE, warn } from "./lib/util.ts";

export const sync = () => {
  const dir = join(ROOT, "episodes");
  const slugs = existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
        .filter((d) => d.isDirectory() && existsSync(paths(d.name).episode))
        .map((d) => d.name)
        .sort()
    : [];

  const bad = slugs.filter((s) => !SLUG_RE.test(s));
  bad.forEach((s) => warn(`skipping episodes/${s}: folder names must be lowercase letters, digits and dashes`));
  const good = slugs.filter((s) => SLUG_RE.test(s));

  const libFile = join(ROOT, "public", "library", "credits.json");
  const imports: string[] = [];
  if (existsSync(libFile)) imports.push('import libCredits from "../public/library/credits.json";');
  const rows: string[] = [];
  good.forEach((slug, i) => {
    const p = paths(slug);
    imports.push(`import e${i} from "../episodes/${slug}/episode.json";`);
    const t = existsSync(p.timing) ? (imports.push(`import t${i} from "../public/episodes/${slug}/timing.json";`), `t${i}`) : "null";
    const a = existsSync(p.assets) ? (imports.push(`import a${i} from "../public/episodes/${slug}/assets.json";`), `a${i}`) : "null";
    const c = existsSync(p.credits) ? (imports.push(`import c${i} from "../public/episodes/${slug}/credits.json";`), `c${i}`) : "null";
    rows.push(`  { slug: ${JSON.stringify(slug)}, episode: e${i}, timing: ${t}, assets: ${a}, credits: ${c}, libraryCredits: lib },`);
  });

  const src = [
    "// Generated by `npm run sync` from the folders in episodes/. Do not edit by hand.",
    'import type { RegistryEntry } from "./kit/Episode";',
    ...imports,
    "",
    `const lib: unknown = ${existsSync(libFile) ? "libCredits" : "null"};`,
    "",
    `export const registry: RegistryEntry[] = [${rows.length ? `\n${rows.join("\n")}\n` : ""}];`,
    "",
  ].join("\n");
  writeFileSync(join(ROOT, "src", "episodes.generated.ts"), src);

  // JSON Schema for editor autocompletion and hover docs in episode.json ("$schema": "../episode.schema.json").
  const json = z.toJSONSchema(episodeSchema, { io: "input", unrepresentable: "any" });
  writeFileSync(join(dir, "episode.schema.json"), JSON.stringify(json, null, 2) + "\n");

  ok(`synced ${good.length} episode${good.length === 1 ? "" : "s"}${good.length ? `: ${good.join(", ")}` : ""}`);
  return good;
};

if (isMain(import.meta.url)) sync();
